/** Maps a source `kind` to its brand logo; falls back to a generic icon. */
export function sourceLogo(kind: string, props: SVGProps<SVGSVGElement> = {}) {
	switch (kind) {
		case "obsidian":
			return <ObsidianLogo {...props} />;
		case "github":
			return <GitHubLogo {...props} />;
		case "notion":
			return <NotionLogo {...props} />;
		case "discord":
			return <DiscordLogo {...props} />;
		case "gdrive":
		case "google-drive":
			return <GoogleDriveLogo {...props} />;
		default:
			return null;
	}
}
